"""LAB 22 (A08 — Software and Data Integrity Failures): unrestricted file upload.

Exploit: upload a file whose name and extension the server keeps. On the
vulnerable build the file lands in the web root with its original name, and
the server serves it back as HTML — so an uploaded .html file is stored XSS
delivered by the bank's own origin, with the bank's own cookies.

After the fix the stored name is generated by the server, the extension is
not the client's to choose, and the file never lands in the web root.
"""

import re

from common import Client, Result, Verdict

ID = 22
TITLE = "Unrestricted file upload — your file, your name, served as HTML"
ENDPOINT = "POST /api/integrity/kyc-upload"
AFFECTED = "backend/src/main/java/com/securebank/labs/a08/IntegrityController.java -> kycUpload(MultipartFile)"

# A file name the attacker controls, with an extension the browser renders.
EVIL_NAME = "kyc-evidence.html"

# The marker in the file's body. If the server serves our bytes back
# unchanged, the upload is live content in the site's origin.
MARKER = "securebank-upload-probe"


def run(ctx: Client) -> Result:
    token = ctx.token("alice")

    body = (
        f"<html><body><script>document.title='{MARKER}'</script>"
        f"<h1>KYC evidence</h1></body></html>"
    ).encode()

    r = ctx.post(
        "/api/integrity/kyc-upload",
        token=token,
        files={"file": (EVIL_NAME, body, "text/html")},
    )

    if r.status_code != 200:
        return Result(
            Verdict.INCONCLUSIVE,
            f"the upload endpoint returned HTTP {r.status_code}: {r.text[:200]}",
        )

    try:
        payload = r.json()
    except ValueError:
        payload = {}

    stored_as = str(payload.get("stored_as") or "")

    # Did the server keep the name we chose?
    name_kept = bool(stored_as) and stored_as.lower().endswith(".html")

    # Is it fetchable, and does the server hand it back as HTML?
    served = None
    if stored_as:
        served = ctx.get(f"/api/integrity/uploads/{stored_as}", token=token)

    served_html = False
    if served is not None and served.status_code == 200:
        content_type = served.headers.get("Content-Type", "")
        if "text/html" in content_type.lower():
            served_html = True
        elif MARKER in served.text:
            served_html = True

    if name_kept or served_html:
        reasons = []
        if name_kept:
            reasons.append(f"the server kept the filename ({stored_as})")
        if served_html:
            reasons.append("the file is served back as HTML from the site's origin")
        return Result(
            Verdict.VULNERABLE,
            "the upload is live content in the site's origin — " + "; ".join(reasons),
        )

    # The name was replaced and the content is not served as HTML.
    if stored_as and re.fullmatch(r"[0-9a-f-]{36}\.[a-z0-9]{1,5}", stored_as):
        return Result(
            Verdict.FIXED,
            f"the stored name was generated by the server ({stored_as}) and the "
            "upload is not served as HTML",
        )

    return Result(
        Verdict.INCONCLUSIVE,
        f"the upload was accepted but the outcome is unclear: stored_as="
        f"{stored_as!r}, location={payload.get('location')!r}",
    )
